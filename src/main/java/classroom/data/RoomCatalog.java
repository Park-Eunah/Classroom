    private static void putCourses(Map<String, String> labels, int roomId, String... weekdays) {
        for (int day = 0; day < weekdays.length; day++) {
            if (weekdays[day].isBlank()) continue;
            for (String entry : weekdays[day].split(";")) {
                String[] parts = entry.split("=", 2);
                if (parts.length != 2) continue;
                String[] range = parts[0].split("-");
                int first = Integer.parseInt(range[0]);
                int last = range.length == 1 ? first : Integer.parseInt(range[1]);
                for (int period = first; period <= last; period++) labels.put(roomId + "-" + day + "-" + period, parts[1]);
            }
        }
    }
    public static boolean hasCourseConflict(Room room, LocalDate date, java.time.LocalTime start, java.time.LocalTime end) {
        int weekday = date.getDayOfWeek().getValue() - 1;
        if (weekday < 0 || weekday >= 5) return false;
        for (int i = 0; i < 14; i++) if (room.weekly[weekday].charAt(i) == '1') {
            java.time.LocalTime classStart = java.time.LocalTime.of(9, 0).plusHours(i);
            java.time.LocalTime classEnd = classStart.plusMinutes(50);
            if (start.isBefore(classEnd) && classStart.isBefore(end)) return true;
        }
        return false;
    }

