    private static String[] busy(String... periodsByDay) {
        String[] result = new String[5];
        for (int d = 0; d < 5; d++) {
            char[] slots = "00000000000000".toCharArray();
            if (!periodsByDay[d].isBlank()) for (String range : periodsByDay[d].split(",")) {
                String[] ends = range.split("-");
                int first = Integer.parseInt(ends[0]);
                int last = ends.length == 1 ? first : Integer.parseInt(ends[1]);
                for (int period = first; period <= last; period++) if (period >= 1 && period <= 14) slots[period - 1] = '1';
            }
            result[d] = new String(slots);
        }
        return result;
    }
